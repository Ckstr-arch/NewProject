// HTTP boundary: mock the transport only; exercise real request/response handling.
const calls = [];
const json = (data, status = 200) => new Response(JSON.stringify(data), { status, headers: { 'Content-Type': 'application/json' } });
const http = createHttpClient({ baseUrl: '/custom/api/', fetcher: async (url, options) => {
  calls.push({ url, options });
  if (url.endsWith('/auth/session')) return json({ success: true, data: { user: null, csrfToken: 'csrf-initial' } });
  if (url.endsWith('/auth/login')) return json({ success: true, data: { user: { id: 1 }, csrfToken: 'csrf-rotated' } });
  if (options.method === 'DELETE') return new Response(null, { status: 204 });
  return json({ success: true, data: [] });
} });
await rejects(() => http.request('POST', '/clubs', {}), 403, 'CSRF_REQUIRED');
